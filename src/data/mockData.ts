/**
 * Calculates Statutory Payroll for an employee:
 * - PF: 12% of Basic salary (up to wage ceiling or standard basic)
 * - ESIC: 0.75% of Gross salary for employee (if Gross <= 21,000)
 * - PT (Professional Tax): ₹200 (standard Maharashtra state slab)
 * - FOS Commission: Based on slabs or assigned %
 */
export function calculatePayrollRecord(
  employee: Employee,
  monthYear: string = 'October 2026',
  workingDays: number = 26,
  presentDays: number = 26,
  totalRecoveryAchieved: number = 0
): PayrollRecord {
  const earnedBaseSalary = Math.round((employee.baseSalary / workingDays) * presentDays);

  // Calculate FOS Commission based on tiers
  let fosCommissionEarned = 0;
  if (employee.role === 'FOS' && totalRecoveryAchieved > 0) {
    if (totalRecoveryAchieved <= 50000) {
      fosCommissionEarned = Math.round(totalRecoveryAchieved * 0.04);
    } else if (totalRecoveryAchieved <= 150000) {
      fosCommissionEarned = Math.round(50000 * 0.04 + (totalRecoveryAchieved - 50000) * 0.07);
    } else {
      fosCommissionEarned = Math.round(
        50000 * 0.04 + 100000 * 0.07 + (totalRecoveryAchieved - 150000) * 0.1
      );
    }
  }

  const incentives = employee.role === 'Telecaller' ? 1500 : 0;
  const grossSalary = earnedBaseSalary + fosCommissionEarned + incentives;

  // Statutory PF: 12% of Basic Salary (Basic usually 50% of base or capped at ₹15,000)
  const basicForPF = Math.min(earnedBaseSalary * 0.5, 15000);
  const pfDeduction = Math.round(basicForPF * 0.12);

  // Statutory ESIC: 0.75% of gross if gross <= ₹21,000, else 0
  const esicDeduction = grossSalary <= 21000 ? Math.round(grossSalary * 0.0075) : 0;

  // Professional Tax: ₹200
  const professionalTax = grossSalary > 10000 ? 200 : 0;

  const totalDeductions = pfDeduction + esicDeduction + professionalTax;
  const netPayableSalary = grossSalary - totalDeductions;

  return {
    id: `pay-${employee.id}-${monthYear.replace(/\s+/g, '-')}`,
    employeeId: employee.id,
    employeeName: employee.name,
    role: employee.role,
    monthYear,
    baseSalary: employee.baseSalary,
    workingDays,
    presentDays,
    earnedBaseSalary,
    totalRecoveryAchieved,
    fosCommissionEarned,
    incentives,
    grossSalary,
    pfDeduction,
    esicDeduction,
    professionalTax,
    otherDeductions: 0,
    totalDeductions,
    netPayableSalary,
    approvalStatus: 'Approved by Admin',
    disbursementDate: '2026-10-07',
  };
}

